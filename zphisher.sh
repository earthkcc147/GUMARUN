##    คุณจะได้รับรหัสต้นฉบับหรือสามารถขอได้หากต้องการ
##    คุณสามารถเปลี่ยนแปลงซอฟต์แวร์หรือใช้บางส่วนในโปรแกรมใหม่ที่เสรี
##    และคุณจะรู้ว่าคุณสามารถทำสิ่งเหล่านี้ได้
