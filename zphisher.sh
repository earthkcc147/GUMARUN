##    คุณสามารถใช้ใบอนุญาตนี้กับโปรแกรมของคุณได้เช่นกัน
##
##    เมื่อเรากล่าวถึงซอฟต์แวร์เสรี เราหมายถึงเสรีภาพ ไม่ใช่ราคา
